// BLOOM — Challenge seed bank BUILD REPORT (BLOOM-036B1, read-only). Reads the shipped bank (content/challenge-seed-banks.js), the build record
// and the candidate cache written by tools/build-challenge-seed-bank.mjs, and writes docs/evidence/bloom-036b/seed-bank/
//   BUILD_REPORT.md       counts, rejections by stage, qualifying rates, archetype / class distribution, proof summary, diversity, builder cost,
//                         hashes, provenance
//   distributions.json    per cell: every diversity feature's range / median over the PASSING candidates vs the RETAINED 50
//   node tools/challenge-bank-report.mjs
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import vm from "node:vm";
import { ROOT, loadEngine } from "./challenge-bank-builder.mjs";

const EVD = path.join(ROOT, "docs/evidence/bloom-036b/seed-bank");
const build = JSON.parse(fs.readFileSync(path.join(EVD, "build.json"), "utf8"));
const candRaw = fs.readFileSync(path.join(EVD, "candidates.json")), cand = JSON.parse(candRaw);
const bankSrc = fs.readFileSync(path.join(ROOT, "content/challenge-seed-banks.js"));
const { D } = loadEngine(), BX = { BLOOM_DATA: { planets: {} } };
vm.runInNewContext(bankSrc.toString("utf8"), { window: BX }); const bank = BX.BLOOM_DATA.challengeSeedBanks;
const sha = b => crypto.createHash("sha256").update(b).digest("hex");
const q = (xs, p) => { if (!xs.length) return null; const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(p * (s.length - 1) + 0.5))]; };
const r2 = x => x == null ? "—" : Math.round(x * 100) / 100, pc = x => x == null ? "—" : `${Math.round(x * 100)} %`;
const STAGES = ["physical", "recipe", "foothold", "species", "cover", "scenario", "quality", "ok"];
const FEAT = ["habitable", "foothold", "waterShare", "landmasses", "meanTemp", "strongRadiation", "dry", "wet", "cold", "hot", "soil", "hazard", "nativeStart", "marginSeconds"];
const featOf = c => ({ habitable: c.habitable, foothold: c.foothold, ...c.features, nativeStart: c.nativeStart ?? null, marginSeconds: c.proof && c.proof.marginSeconds });

const keys = Object.keys(build.cells), dist = {}, L = [];
for (const k of keys) {
  const pass = cand.rows.filter(r => r.cells && r.cells[k] && r.cells[k].stage === "ok"), cell = bank.cells[k];
  const kept = new Set(cell ? cell.entries.map(e => e.fingerprint) : []), ret = pass.filter(r => kept.has(r.physical.fingerprint));
  dist[k] = {};
  for (const f of FEAT) { const P = pass.map(r => featOf(r.cells[k])[f]).filter(x => x != null), R = ret.map(r => featOf(r.cells[k])[f]).filter(x => x != null);
    if (!P.length) continue; dist[k][f] = { passing: { min: q(P, 0), median: q(P, 0.5), max: q(P, 1) }, retained: { min: q(R, 0), median: q(R, 0.5), max: q(R, 1) } }; }
}
fs.writeFileSync(path.join(EVD, "distributions.json"), JSON.stringify(dist, null, 1) + "\n");

const P = s => L.push(s);
P("# BLOOM-036B1 — Challenge seed bank build report");
P("");
P(`Generated by [\`tools/challenge-bank-report.mjs\`](../../../../tools/challenge-bank-report.mjs) from [\`build.json\`](build.json), [\`candidates.json\`](candidates.json) and the shipped`);
P(`bank [\`content/challenge-seed-banks.js\`](../../../../content/challenge-seed-banks.js). Design: [\`docs/CHALLENGES_SYSTEM_v1.md\`](../../../CHALLENGES_SYSTEM_v1.md) §4.`);
P("Builder: `node tools/build-challenge-seed-bank.mjs --per-archetype 160 --workers 8` (resumable with `--reuse`; `--check` = the shipped bank is");
P("exactly a rebuild from the cached candidates).");
P("");
P("## 1. Build");
P("");
P("| | |");
P("|---|---|");
P(`| Pool | ${build.pool.worlds} worlds = ${D.archetypes.length} archetypes × ${build.pool.perArchetype} World Seeds, stream \`${build.pool.stream}\` (species- and Challenge-free) |`);
P(`| Physical validation passed | ${build.pool.physicalOk} / ${build.pool.worlds} (the production generation path: archetype layers 1–8, its accepted attempt) |`);
P(`| Cells | ${keys.length} (every released Challenge × each species it allows: player choice = 4 cells, a prescribed plant = 1), target ${build.target} entries each |`);
P(`| Result | ${build.limitingCells.length ? `**LIMITING CELLS:** ${build.limitingCells.join("; ")}` : `every cell holds ${build.target}; **not provisional**`} |`);
P(`| Validation per candidate | species evaluation + S2 (from the prescribed start if any) → recipe → the scenario's layer P at the validator's FULL budget with every confirmation run → Challenge quality |`);
P(`| Builder | ${build.workers} worker threads on ${build.hardwareThreads} hardware threads · wall ${Math.round(build.wallSeconds / 60)} min${build.wallSeconds < 60 ? " (candidate cache reused)" : ""} · git ${build.gitHead} |`);
P(`| Inputs fingerprint | \`${build.inputsFingerprint}\` (every cell's provenance; a change re-evaluates every candidate) |`);
P(`| Bank | ${build.bankBytes} bytes · sha256 \`${build.bankSha256}\` |`);
P(`| Candidate cache | ${candRaw.length} bytes · sha256 \`${sha(candRaw)}\` |`);
P("");
P("## 2. Accepted / rejected — per Challenge × species");
P("");
P("Rejection stages, in order: **physical** (no accepted attempt) · **recipe** (archetype or arrival band) · **foothold** (S1 floor; unused) · **species** (S2 not winnable) · **cover** (native");
P("cover floor; unused) · **scenario** (layer P failed) · **quality** (passed, but the mechanic did not matter in the proof). (Physical failures are the same worlds in every cell.)");
P("");
P(`| Cell | evaluated | ${STAGES.join(" | ")} | qualifying | retained | barely-passing held back | retained by archetype | retained by class |`);
P(`|---|---:|${STAGES.map(() => "---:").join("|")}|---:|---:|---:|---|---|`);
for (const k of keys) { const c = build.cells[k];
  P(`| \`${k}\` | ${c.evaluated} | ${STAGES.map(s => c.stages[s] || 0).join(" | ")} | ${c.passing} (${c.qualifyingPct} %) | **${c.retained}** | ${c.deprioritized} | ${Object.entries(c.retainedByArchetype).map(([a, n]) => `${a.replace(/_.*/, "")} ${n}`).join(" · ")} | ${Object.entries(c.retainedByClass).map(([a, n]) => `${a} ${n}`).join(" · ")} |`); }
P("");
P("## 3. Proof summary (the retained entries)");
P("");
P("Every retained entry: layer P **PASS** at the full budget, confirmations included; S2 winnable. Medians over the 50 entries. Confirmation runs");
P("follow each scenario's own `validation.confirmRngSeeds` (Native Competition and Volatile Climate: 2 seeds per witness; Dying World is deterministic: none).");
P("");
P("| Cell | all PASS | simulations (sum / median) | confirmation runs | witness margin s (median, min–max) | hold coverage (min) | mechanic in the proof |");
P("|---|---|---|---:|---|---:|---|");
for (const k of keys) { const E = (bank.cells[k] || { entries: [] }).entries, pr = E.map(e => e.proof);
  const ch = k.split("/")[0], mech = ch === "native_competition" ? `contested fronts median ${q(pr.map(p => p.contested || 0), 0.5)} (min ${q(pr.map(p => p.contested || 0), 0)})`
    : ch === "dying_world" ? `decline done at the margin min ${pc(q(pr.map(p => p.pressureAtMargin || 0), 0))}` : `climate shocks median ${q(pr.map(p => p.shocks || 0), 0.5)}`;
  P(`| \`${k}\` | ${E.length && E.every(e => e.proof.status === "PASS" && e.s2) ? "yes" : "**NO**"} | ${pr.reduce((a, p) => a + (p.simulations || 0), 0)} / ${q(pr.map(p => p.simulations || 0), 0.5)} | ${pr.reduce((a, p) => a + (p.confirmations || 0), 0)} | ${q(pr.map(p => p.marginSeconds || 0), 0.5)} (${q(pr.map(p => p.marginSeconds || 0), 0)}–${q(pr.map(p => p.marginSeconds || 0), 1)}) | ${r2(q(pr.map(p => p.holdCoverage || 0), 0))} | ${mech} |`); }
P("");
P("## 4. Diversity (curation)");
P("");
P("Curation is deterministic: archetype quotas, then farthest-point selection on normalized features; the lowest decile of witness hold margin is");
P("held back unless needed. **Min pair distance** = the smallest normalized feature distance between any two retained entries (0 would be a");
P("near-duplicate). Ranges: passing candidates → retained 50 (full table: [`distributions.json`](distributions.json)).");
P("");
P("| Cell | min pair distance | distinct buckets | arrival share | foothold | water | mean temperature | witness margin s |");
P("|---|---:|---:|---|---|---|---|---|");
const rng = (k, f, fmt = r2) => { const d = dist[k][f]; return d ? `${fmt(d.passing.min)}–${fmt(d.passing.max)} → ${fmt(d.retained.min)}–${fmt(d.retained.max)}` : "—"; };
for (const k of keys) { const E = (bank.cells[k] || { entries: [] }).entries;
  P(`| \`${k}\` | ${build.cells[k].minPairDistance} | ${new Set(E.map(e => e.bucket)).size} | ${rng(k, "habitable", pc)} | ${rng(k, "foothold", pc)} | ${rng(k, "waterShare", pc)} | ${rng(k, "meanTemp")} | ${rng(k, "marginSeconds", x => Math.round(x))} |`); }
P("");
P("## 5. Builder cost (CPU, summed over worker threads)");
P("");
P("| Cell | species evaluation s | layer-P proof s | proof s per retained entry |");
P("|---|---:|---:|---:|");
for (const k of keys) { const c = build.cells[k]; P(`| \`${k}\` | ${c.cpuSeconds.species} | ${c.cpuSeconds.proof} | ${c.retained ? Math.round(c.cpuSeconds.proof / c.retained) : "—"} |`); }
const nc = keys.filter(k => k.startsWith("native_competition/")), tot = keys.reduce((a, k) => a + build.cells[k].cpuSeconds.proof, 0), ncs = nc.reduce((a, k) => a + build.cells[k].cpuSeconds.proof, 0);
P("");
P(`Native Competition is ${Math.round(100 * ncs / tot)} % of all proof CPU (${ncs} of ${tot} s) — the cost the live search used to put in front of the player`);
P("([`../NATIVE_COMPETITION_LATENCY_STUDY.md`](../NATIVE_COMPETITION_LATENCY_STUDY.md), superseded). It is now paid once, offline.");
P("");
P("## 6. Provenance (stale-bank protection)");
P("");
P("Every cell carries the provenance it was built against; the runtime recomputes it from the running game at every launch and refuses any");
P("difference (`STALE_BANK`). Example — `native_competition/organic_hybrid`:");
P("");
P("```json");
P(JSON.stringify((bank.cells["native_competition/organic_hybrid"] || {}).provenance || null, null, 1));
P("```");
P("");
P("An entry carries what regenerates and verifies the exact world plus its proof provenance — never geometry. Example (entry 0 of that cell):");
P("");
P("```json");
P(JSON.stringify(((bank.cells["native_competition/organic_hybrid"] || {}).entries || [])[0] || null));
P("```");
P("");
P(`Hashes: bank sha256 \`${sha(bankSrc)}\` · build.json sha256 \`${sha(fs.readFileSync(path.join(EVD, "build.json")))}\` · distributions.json sha256 \`${sha(fs.readFileSync(path.join(EVD, "distributions.json")))}\`.`);
fs.writeFileSync(path.join(EVD, "BUILD_REPORT.md"), L.join("\n") + "\n");
console.log(`wrote ${path.relative(ROOT, path.join(EVD, "BUILD_REPORT.md"))} + distributions.json (${keys.length} cells)`);
